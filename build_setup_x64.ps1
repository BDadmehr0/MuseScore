function Invoke-CleanStep {
    Write-Step 'Cleaning previous build output'
    foreach ($dir in @('build.release', 'build.install', 'build.artifacts', 'msvc.build', 'msvc.install')) {
        $full = Join-Path $RepoRoot $dir
        if (Test-Path -LiteralPath $full) {
            Write-Info "removing $dir"
            Remove-Item -LiteralPath $full -Recurse -Force -ErrorAction SilentlyContinue
        }
    }
    Write-Ok 'Clean done.'
}

function Invoke-SubmodulesStep {
    Write-Step 'Updating git submodules (muse_framework, muse_deps)'
    if ($SkipSubmodules) { Write-Info 'Skipped (-SkipSubmodules).'; return }

    Invoke-CmdScript -Title 'git submodule update' `
                     -CommandLine 'git submodule update --init --recursive'
    Write-Ok 'Submodules are up to date.'
}

function Invoke-DependenciesStep {
    Write-Step 'Downloading Windows dependencies (setup.bat)'

    if ($SkipDeps) { Write-Info 'Skipped (-SkipDeps).'; return }

    if ((Test-Path -LiteralPath $DepsDir) -and (Test-Path -LiteralPath $JackDir)) {
        Write-Info "Dependencies already present in '$DepsDir'."
        if (-not (Confirm-Continue 'Download them again?')) {
            Write-Ok 'Using the existing dependencies.'
            return
        }
    }

    $portableArg = if ($Portable) { ' --portable ON' } else { '' }
    Invoke-CmdScript -Title 'setup.bat' -CommandLine ('{0}{1}' -f $SetupBat, $portableArg)

    if (-not (Test-Path -LiteralPath $DepsDir)) {
        throw "setup.bat finished but '$DepsDir' does not exist. Check your internet connection / proxy."
    }
    Add-ToPathFront $JackDir
    Write-Ok 'Dependencies installed.'
}

function Resolve-BuildNumber {
    if ($BuildNumber) {
        if ($BuildNumber -notmatch '^\d+$') {
            throw "BuildNumber must be numeric, got '$BuildNumber'."
        }
        if ($BuildNumber.Length -gt 9) {
            throw "BuildNumber must be at most 9 digits (WiX stores it in an Int32), got '$BuildNumber'."
        }
        return $BuildNumber
    }
    # Same rule as buildscripts/ci/tools/make_build_number.sh
    return ((Get-Date).ToUniversalTime().ToString('yyMMddHHmm')).Substring(0, 9)
}

function Invoke-MetadataStep {
    param([string] $Number)

    Write-Step 'Generating build metadata (build_mode.env / build_number.env)'

    New-Item -ItemType Directory -Path $EnvDir -Force | Out-Null

    Invoke-BashScript -Title 'make_build_mode_env.sh' -Arguments @(
        './buildscripts/ci/tools/make_build_mode_env.sh', '-e', 'workflow_dispatch', '-m', $BuildMode)

    Invoke-BashScript -Title 'make_build_number.sh' -Arguments @(
        './buildscripts/ci/tools/make_build_number.sh', $Number)

    foreach ($file in @('build_mode.env', 'build_number.env')) {
        $full = Join-Path $EnvDir $file
        if (-not (Test-Path -LiteralPath $full)) {
            throw "$file was not created. Is bash (Git Bash) working correctly?"
        }
        $value = Get-EnvFileValue -Path $full
        if (-not $value) { throw "$file is empty." }
        Write-Ok ("{0} = {1}" -f $file, $value)
    }
}

function Invoke-BuildStep {
    param([string] $Number)

    Write-Step 'Building MuseScore Studio (RelWithDebInfo + install)'
    Write-Info 'This is the long part: expect 2-4+ hours for a first build.'

    $portableArg = if ($Portable) { ' --portable ON' } else { '' }
    $commandLine = '{0} -n {1} --dockwidgets_v2 {2}{3}' -f $BuildBat, $Number, $DockWidgetsV2, $portableArg

    Invoke-CmdScript -Title 'build.bat' -CommandLine $commandLine

    $exeName = 'MuseScoreStudio5.exe'
    $exePath = if ($Portable) {
        Join-Path $InstallDir ('App\MuseScore\bin\{0}' -f $exeName)
    } else {
        Join-Path $InstallDir ('bin\{0}' -f $exeName)
    }

    if (-not (Test-Path -LiteralPath $BuildDir)) {
        throw "build.release was not created - the build failed. See the log above."
    }
    if (-not (Test-Path -LiteralPath $exePath)) {
        Write-Warn "Expected executable not found at: $exePath"
        Write-Warn 'The packaging step will probably fail. Check the build log for errors.'
    }
    else {
        Write-Ok "Built: $exePath"
    }
}

function New-PatchedPackageScript {
    <#
        package.bat hard-codes
            SET UUIDGEN="C:\Program Files (x86)\Windows Kits\10\bin\10.0.26100.0\x64\uuidgen.exe"
        which does not exist on most machines. Instead of editing the repository file
        we write a patched copy into build.artifacts (git-ignored) and run that.
        Returns a path relative to the repository root (so it never contains spaces).
    #>
    $originalPath = Join-Path $RepoRoot $PackageBat
    $content      = Get-Content -LiteralPath $originalPath -Raw
    $uuidgen      = Get-UuidGenPath

    if ($uuidgen -and $content.Contains($uuidgen)) {
        Write-Info "Using uuidgen: $uuidgen (package.bat already points at it)"
        return $PackageBat
    }

    if ($uuidgen) {
        $uuidgenLine = 'SET UUIDGEN="' + $uuidgen + '"'
        $productGuid = $null
        Write-Info "Using uuidgen: $uuidgen"
    }
    else {
        $uuidgenLine = 'REM UUIDGEN not available, GUID generated by build_setup_x64.ps1'
        $productGuid = [guid]::NewGuid().ToString().ToUpperInvariant()
        Write-Info 'No uuidgen.exe found in the Windows SDK - generating the product GUID with PowerShell.'
        Write-Info "Product GUID: $productGuid"
    }

    $patchedLines = New-Object System.Collections.Generic.List[string]
    $replacedUuidGen = $false
    $replacedCall    = $false

    foreach ($line in ($content -split "`r?`n")) {
        if ($line -match '^\s*SET UUIDGEN=') {
            $patchedLines.Add($uuidgenLine) | Out-Null
            $replacedUuidGen = $true
        }
        elseif ($productGuid -and ($line -match '^\s*%UUIDGEN%\s*>\s*uuid\.txt\s*$')) {
            # No trailing space before '>' or SET /p would read the space as well.
            $patchedLines.Add(('ECHO {0}> uuid.txt' -f $productGuid)) | Out-Null
            $replacedCall = $true
        }
        else {
            $patchedLines.Add($line) | Out-Null
        }
    }

    if (-not $replacedUuidGen) {
        Write-Warn 'Could not find the "SET UUIDGEN=" line in package.bat - using the original script.'
        return $PackageBat
    }
    if ($productGuid -and -not $replacedCall) {
        Write-Warn 'Could not find the uuidgen call in package.bat - using the original script.'
        return $PackageBat
    }

    New-Item -ItemType Directory -Path $ArtifactsDir -Force | Out-Null
    $relativePath = 'build.artifacts\package_x64.generated.bat'
    $patchedPath  = Join-Path $RepoRoot $relativePath
    Set-Content -LiteralPath $patchedPath -Value ($patchedLines -join "`r`n") -Encoding ASCII
    Write-Info "Patched package script: $relativePath"
    return $relativePath
}

function Confirm-PackageEnvFiles {
    param([string] $Number)

    # build.bat normally creates these; regenerate them for -PackageOnly runs.
    $required = @{
        'build_mode.env'     = @('./buildscripts/ci/tools/make_build_mode_env.sh', '-e', 'workflow_dispatch', '-m', $BuildMode)
        'build_number.env'   = @('./buildscripts/ci/tools/make_build_number.sh', $Number)
        'build_revision.env' = @('./buildscripts/ci/tools/make_revision_env.sh')
        'build_version.env'  = @('./buildscripts/ci/tools/make_version_env.sh', $Number)
        'build_branch.env'   = @('./buildscripts/ci/tools/make_branch_env.sh')
    }

    New-Item -ItemType Directory -Path $EnvDir -Force | Out-Null

    foreach ($file in @($required.Keys)) {
        $full  = Join-Path $EnvDir $file
        $value = Get-EnvFileValue -Path $full
        if (-not $value) {
            Write-Info "$file missing or empty - regenerating"
            Invoke-BashScript -Title ("regenerate {0}" -f $file) -Arguments $required[$file]
        }
    }

    foreach ($file in @($required.Keys)) {
        $full  = Join-Path $EnvDir $file
        $value = Get-EnvFileValue -Path $full
        if (-not $value) {
            throw "build.artifacts\env\$file is missing or empty - see docs/windows-build-troubleshooting.md"
        }
        Write-Ok ("{0} = {1}" -f $file, $value)
    }
}

function Invoke-PackageStep {
    param([string] $Number)

    Write-Step 'Creating the installer (package.bat)'

    if (-not (Test-Path -LiteralPath $BuildDir)) {
        throw @"
build.release does not exist, so packaging cannot run.
Run the build first:
    .\build_setup_x64.ps1 -BuildMode $BuildMode
(see docs/windows-build-troubleshooting.md, section 1: "CMake Error: The source directory ...")
"@
    }
    if (-not (Test-Path -LiteralPath (Join-Path $BuildDir 'CMakeCache.txt'))) {
        throw "build.release exists but is not configured (no CMakeCache.txt). Re-run the build step."
    }
    if (-not (Test-Path -LiteralPath $InstallDir)) {
        throw "build.install does not exist. Run the build step before packaging."
    }

    Confirm-PackageEnvFiles -Number $Number

    $packageScript = New-PatchedPackageScript
    $portableArg   = if ($Portable) { ' --portable ON' } else { '' }
    $commandLine   = '{0} -m {1} --guid {2}{3}' -f $packageScript, $BuildMode, $UpgradeGuid, $portableArg

    Invoke-CmdScript -Title 'package.bat' -CommandLine $commandLine
    Write-Ok 'Packaging finished.'
}

function Invoke-ChecksumStep {
    Write-Step 'Creating the checksum'
    $artifactNameFile = Join-Path $EnvDir 'artifact_name.env'
    if (-not (Test-Path -LiteralPath $artifactNameFile)) {
        Write-Warn 'artifact_name.env not found - skipping the checksum.'
        return
    }
    Invoke-BashScript -Title 'checksum.sh' -AllowFailure `
                      -Arguments @('./buildscripts/ci/tools/checksum.sh')

    $checksumFile = Join-Path $ArtifactsDir 'checksum.txt'
    if (Test-Path -LiteralPath $checksumFile) {
        Write-Ok "checksum: $checksumFile"
        Get-Content -LiteralPath $checksumFile | ForEach-Object { Write-Note $_ }
    }
}

function Write-Summary {
    $elapsed = (Get-Date) - $script:StartTime

    Write-Host ''
    Write-Host ('=' * 78) -ForegroundColor DarkGreen
    Write-Host '  SUMMARY' -ForegroundColor Green
    Write-Host ('=' * 78) -ForegroundColor DarkGreen

    Write-Host ("  Build mode : {0}{1}" -f $BuildMode, $(if ($Portable) { ' (PortableApps)' } else { '' }))
    Write-Host ("  Elapsed    : {0:hh\:mm\:ss}" -f $elapsed)

    if (Test-Path -LiteralPath $ArtifactsDir) {
        $artifacts = Get-ChildItem -LiteralPath $ArtifactsDir -File -ErrorAction SilentlyContinue |
                     Where-Object { $_.Extension -in @('.msi', '.exe', '.7z') } |
                     Sort-Object LastWriteTime -Descending
        if ($artifacts) {
            Write-Host '  Artifacts  :' -ForegroundColor Green
            foreach ($artifact in $artifacts) {
                Write-Host ("    {0}  ({1:N1} MB)" -f $artifact.FullName, ($artifact.Length / 1MB)) -ForegroundColor Green
            }
        }
        else {
            Write-Host "  Artifacts  : none found in $ArtifactsDir" -ForegroundColor Yellow
        }
    }

    $exePath = if ($Portable) {
        Join-Path $InstallDir 'App\MuseScore\bin\MuseScoreStudio5.exe'
    } else {
        Join-Path $InstallDir 'bin\MuseScoreStudio5.exe'
    }
    if (Test-Path -LiteralPath $exePath) {
        Write-Host "  Executable : $exePath"
    }

    if ($script:Warnings.Count -gt 0) {
        Write-Host ''
        Write-Host ("  {0} warning(s):" -f $script:Warnings.Count) -ForegroundColor Yellow
        foreach ($warning in $script:Warnings) { Write-Host "    - $warning" -ForegroundColor Yellow }
    }

    Write-Host ''
    Write-Host '  Unsigned installers are normal here; Windows SmartScreen may show' -ForegroundColor DarkGray
    Write-Host '  an "unknown publisher" warning when you run them.' -ForegroundColor DarkGray
    Write-Host ''
}

