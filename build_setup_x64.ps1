function Invoke-CmdScript {
    # NOTE: $CommandLine must not contain double quotes. Windows PowerShell escapes
    # embedded quotes with a backslash when it builds the native command line, and
    # cmd.exe does not understand that escaping. All paths used here are relative to
    # the repository root, so they never contain spaces.
    param(
        [Parameter(Mandatory = $true)][string] $CommandLine,
        [Parameter(Mandatory = $true)][string] $Title,
        [switch] $AllowFailure
    )
    if ($CommandLine.Contains('"')) {
        throw "Internal error: command line must not contain quotes: $CommandLine"
    }
    Write-Info "cmd> $CommandLine"
    $global:LASTEXITCODE = 0
    & cmd.exe /d /s /c $CommandLine
    $script:LastNativeExitCode = $LASTEXITCODE
    if ($script:LastNativeExitCode -ne 0 -and -not $AllowFailure) {
        throw "$Title failed with exit code $script:LastNativeExitCode`n       Command: $CommandLine"
    }
}

function Invoke-BashScript {
    param(
        [Parameter(Mandatory = $true)][string[]] $Arguments,
        [Parameter(Mandatory = $true)][string]   $Title,
        [switch] $AllowFailure
    )
    if (-not $script:BashExe) {
        throw "bash was not resolved. Install Git for Windows (Git Bash) and re-run."
    }
    Write-Info ("bash> {0}" -f ($Arguments -join ' '))
    $global:LASTEXITCODE = 0
    & $script:BashExe @Arguments
    $script:LastNativeExitCode = $LASTEXITCODE
    if ($script:LastNativeExitCode -ne 0 -and -not $AllowFailure) {
        throw "$Title failed with exit code $script:LastNativeExitCode"
    }
}

function Get-EnvFileValue {
    # Reads the first line of a build.artifacts\env\*.env file, tolerating
    # missing/empty files (returns $null instead of throwing).
    param([string] $Path)
    if (-not (Test-Path -LiteralPath $Path)) { return $null }
    $line = Get-Content -LiteralPath $Path -TotalCount 1 -ErrorAction SilentlyContinue |
            Select-Object -First 1
    if ($null -eq $line) { return $null }
    $line = ([string]$line).Trim()
    if (-not $line) { return $null }
    return $line
}

function Get-CommandPath {
    param([string] $Name)
    $cmd = Get-Command $Name -CommandType Application -ErrorAction SilentlyContinue |
           Select-Object -First 1
    if ($cmd) { return $cmd.Source }
    return $null
}

function Add-ToPathFront {
    param([string] $Directory)
    if (-not $Directory) { return }
    if (-not (Test-Path -LiteralPath $Directory)) { return }
    $current = $env:PATH -split ';' | Where-Object { $_ }
    if ($current -notcontains $Directory) {
        $env:PATH = "$Directory;$env:PATH"
    }
}

