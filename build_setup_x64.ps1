function Test-Administrator {
    $identity  = [Security.Principal.WindowsIdentity]::GetCurrent()
    $principal = New-Object Security.Principal.WindowsPrincipal($identity)
    return $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
}

function Invoke-SelfElevation {
    param($BoundParameters)

    $exeName = if ($PSVersionTable.PSEdition -eq 'Core') { 'pwsh.exe' } else { 'powershell.exe' }

    $argList = @('-NoLogo', '-NoProfile', '-ExecutionPolicy', 'Bypass', '-NoExit',
                 '-File', ('"{0}"' -f $PSCommandPath))

    if ($BoundParameters) {
        foreach ($entry in $BoundParameters.GetEnumerator()) {
            if ($entry.Key -eq 'NoElevate') { continue }
            $value = $entry.Value
            if ($value -is [System.Management.Automation.SwitchParameter]) {
                if ($value.IsPresent) { $argList += ('-{0}' -f $entry.Key) }
            }
            elseif ($value -is [bool]) {
                if ($value) { $argList += ('-{0}' -f $entry.Key) }
            }
            else {
                $argList += ('-{0}' -f $entry.Key)
                $argList += ('"{0}"' -f $value)
            }
        }
    }

    Write-Host ''
    Write-Host '  This script needs Administrator rights (setup.bat writes to' -ForegroundColor Yellow
    Write-Host "  C:\musescore_dependencies and 'C:\Program Files (x86)\Jack')." -ForegroundColor Yellow
    Write-Host '  Re-launching in an elevated PowerShell window...' -ForegroundColor Yellow
    Write-Host ("  {0} {1}" -f $exeName, ($argList -join ' ')) -ForegroundColor DarkGray

    Start-Process -FilePath $exeName -Verb RunAs -ArgumentList $argList -WorkingDirectory $RepoRoot
}

