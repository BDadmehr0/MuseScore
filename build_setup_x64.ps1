try {
    New-Item -ItemType Directory -Path (Join-Path $ArtifactsDir 'logs') -Force | Out-Null
    $logPath = Join-Path $ArtifactsDir ('logs\build_setup_x64_{0}.log' -f (Get-Date -Format 'yyyyMMdd_HHmmss'))
    Start-Transcript -Path $logPath -Force | Out-Null
    $transcriptStarted = $true
    Write-Host ("  Log file   : {0}" -f $logPath)
}
catch {
    Write-Host '  [info] Could not start a transcript log (continuing without it).' -ForegroundColor Gray
}

$exitCode = 0
try {
    Test-Prerequisites

    if ($CheckOnly) {
        Write-Host ''
        Write-Ok 'Check finished - this machine is ready to build the x64 setup.'
        Write-Host ''
        Write-Host '  Next:  .\build_setup_x64.ps1 -BuildMode stable' -ForegroundColor Cyan
    }
    else {
        $resolvedNumber = Resolve-BuildNumber
        Write-Info "Build number: $resolvedNumber"

        if ($Clean) {
            if ($PackageOnly) {
                Write-Warn '-Clean is ignored together with -PackageOnly (it would delete the build you want to package).'
            }
            else {
                Invoke-CleanStep
            }
        }

        if (-not $PackageOnly) {
            Invoke-SubmodulesStep
            Invoke-DependenciesStep
            Invoke-MetadataStep -Number $resolvedNumber
            Invoke-BuildStep    -Number $resolvedNumber
        }
        else {
            Write-Info 'Skipping submodules/dependencies/build (-PackageOnly).'
        }

        if (-not $BuildOnly) {
            Invoke-PackageStep -Number $resolvedNumber
            Invoke-ChecksumStep
        }
        else {
            Write-Info 'Skipping packaging (-BuildOnly).'
        }

        Write-Summary
    }
}
catch {
    Write-FailureHelp -Message $_.Exception.Message
    if ($_.ScriptStackTrace) { Write-Verbose $_.ScriptStackTrace }
    $exitCode = 1
}
finally {
    if ($transcriptStarted) {
        try { Stop-Transcript | Out-Null } catch { }
    }
}

exit $exitCode
