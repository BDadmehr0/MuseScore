    param([string] $Message)

    Write-Host ''
    Write-Host ('=' * 78) -ForegroundColor DarkRed
    Write-Host '  BUILD FAILED' -ForegroundColor Red
    Write-Host ('=' * 78) -ForegroundColor DarkRed
    Write-Host "  $Message" -ForegroundColor Red
    Write-Host ''
    Write-Host '  Troubleshooting:' -ForegroundColor Yellow
    Write-Host '    * docs/windows-build-troubleshooting.md  - known errors and fixes'
    Write-Host '    * docs/local-windows-x64-setup.md        - full setup guide (Persian)'
    Write-Host '    * "WSL ERROR: execvpe(/bin/bash) failed" -> install Git for Windows (Git Bash)'
    Write-Host '    * "The system cannot find the path specified" while reading *.env'
    Write-Host '      -> re-run without -PackageOnly so build.bat regenerates the env files'
    Write-Host '    * "CMake Error: The source directory ... does not contain CMakeLists.txt"'
    Write-Host '      -> build.release is missing/broken; run a full build (add -Clean)'
    Write-Host '    * Re-run just the check with:  .\build_setup_x64.ps1 -CheckOnly'
    Write-Host ''
}

