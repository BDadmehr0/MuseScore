Write-Host ''
Write-Host '################################################################################' -ForegroundColor Magenta
Write-Host '#   MuseScore Studio / Persian Tuner  -  Windows x64 setup builder             #' -ForegroundColor Magenta
Write-Host '#   docs/local-windows-x64-setup.md  +  docs/windows-build-troubleshooting.md  #' -ForegroundColor Magenta
Write-Host '################################################################################' -ForegroundColor Magenta
Write-Host ("  Repository : {0}" -f $RepoRoot)
try {
    Write-Host ("  Branch     : {0}" -f (& git rev-parse --abbrev-ref HEAD 2>$null))
    Write-Host ("  Commit     : {0}" -f (& git rev-parse --short=7 HEAD 2>$null))
