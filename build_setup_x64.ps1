function Resolve-Bash {
    # The WSL stub at C:\Windows\System32\bash.exe is what produces
    # "WSL ERROR: execvpe(/bin/bash) failed" in the build logs, so Git Bash wins.
    $gitBashCandidates = @()

    $gitExe = Get-CommandPath 'git.exe'
    if ($gitExe) {
        $gitRoot = Split-Path -Parent (Split-Path -Parent $gitExe)   # ...\Git\cmd\git.exe -> ...\Git
        $gitBashCandidates += (Join-Path $gitRoot 'bin\bash.exe')
    }
    $gitBashCandidates += 'C:\Program Files\Git\bin\bash.exe'
    $gitBashCandidates += 'C:\Program Files (x86)\Git\bin\bash.exe'
    $gitBashCandidates += (Join-Path $env:LOCALAPPDATA 'Programs\Git\bin\bash.exe')

    foreach ($candidate in $gitBashCandidates) {
        if ($candidate -and (Test-Path -LiteralPath $candidate)) {
            $script:BashExe = (Resolve-Path -LiteralPath $candidate).Path
            Add-ToPathFront (Split-Path -Parent $script:BashExe)
            Write-Ok "Git Bash: $script:BashExe"
            return $true
        }
    }

    $anyBash = Get-CommandPath 'bash.exe'
    if ($anyBash) {
        if ($anyBash -like "$env:SystemRoot\System32\*") {
            Write-Warn "Only the WSL bash stub was found ($anyBash). The CI scripts expect Git Bash;"
            Write-Warn "if the build dies with 'WSL ERROR: execvpe(/bin/bash) failed', install Git for Windows."
        }
        $script:BashExe = $anyBash
        Write-Ok "bash: $anyBash"
        return $true
    }

    Write-Fail 'bash not found. Install Git for Windows (includes Git Bash):  choco install -y git'
    return $false
}

function Resolve-VisualStudio {
    $vswhere = Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio\Installer\vswhere.exe'
    if (-not (Test-Path -LiteralPath $vswhere)) {
        Write-Fail 'vswhere.exe not found -> Visual Studio 2022 (or Build Tools) is not installed.'
        Write-Note 'Install "Desktop development with C++" with MSVC v143 x64/x86 and a Windows 11 SDK.'
        return $false
    }

    $installPath = & $vswhere -latest -products '*' `
        -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 `
        -property installationPath 2>$null | Select-Object -First 1

    if (-not $installPath) {
        Write-Fail 'No Visual Studio installation with the MSVC x64 toolset was found.'
        Write-Note 'Add the workload "Desktop development with C++" (MSVC v143) in the VS Installer.'
        return $false
    }

    $vcvars = Join-Path $installPath 'VC\Auxiliary\Build\vcvars64.bat'
    if (-not (Test-Path -LiteralPath $vcvars)) {
        Write-Fail "vcvars64.bat not found in $installPath (ninja_build.bat needs it)."
        return $false
    }

    Write-Ok "Visual Studio: $installPath"
    return $true
}

function Resolve-Qt {
    $candidates = @()
    if ($QtDir)             { $candidates += $QtDir }
    if ($env:QT_DIR)        { $candidates += $env:QT_DIR }
    if ($env:QTDIR)         { $candidates += $env:QTDIR }
    if ($env:QT_ROOT_DIR)   { $candidates += $env:QT_ROOT_DIR }

    if (-not $candidates) {
        foreach ($root in @('C:\Qt', 'D:\Qt', (Join-Path $env:SystemDrive 'Qt'))) {
            if (-not (Test-Path -LiteralPath $root)) { continue }
            $found = Get-ChildItem -LiteralPath $root -Directory -ErrorAction SilentlyContinue |
                     Where-Object { $_.Name -match '^6\.\d+' } |
                     Sort-Object { try { [version]$_.Name } catch { [version]'0.0' } } -Descending
            foreach ($versionDir in $found) {
                foreach ($abi in @('msvc2022_64', 'msvc2019_64')) {
                    $p = Join-Path $versionDir.FullName $abi
                    if (Test-Path -LiteralPath $p) { $candidates += $p }
                }
            }
        }
    }

    $qtHome = $null
    foreach ($candidate in $candidates) {
        if ($candidate -and (Test-Path -LiteralPath (Join-Path $candidate 'bin\qmake.exe'))) {
            $qtHome = (Resolve-Path -LiteralPath $candidate).Path
            break
        }
    }

    if (-not $qtHome) {
        Write-Fail 'Qt 6 (msvc2022_64) not found.'
        Write-Note 'Install Qt 6.10.2 "MSVC 2022 64-bit" plus the modules qt5compat,'
        Write-Note 'qtnetworkauth, qtshadertools, qtwebsockets - or pass -QtDir <path>.'
        Write-Note 'aqtinstall:  aqt install-qt windows desktop 6.10.2 win64_msvc2022_64 -O C:\Qt -m qt5compat qtnetworkauth qtshadertools qtwebsockets'
        return $false
    }

    if (-not (Test-Path -LiteralPath (Join-Path $qtHome 'bin\windeployqt.exe'))) {
        Write-Warn "windeployqt.exe missing in $qtHome\bin - the install step will fail."
    }

    # Required Qt modules (the build fails late and cryptically when one is missing)
    $requiredModules = @{
        'Qt6Core5Compat'  = 'qt5compat'
        'Qt6NetworkAuth'  = 'qtnetworkauth'
        'Qt6ShaderTools'  = 'qtshadertools'
        'Qt6WebSockets'   = 'qtwebsockets'
    }
    foreach ($module in $requiredModules.Keys) {
        $cmakeDir = Join-Path $qtHome ('lib\cmake\{0}' -f $module)
        if (-not (Test-Path -LiteralPath $cmakeDir)) {
            Write-Warn ("Qt module '{0}' ({1}) seems to be missing in this Qt installation." -f $requiredModules[$module], $module)
        }
    }

    $env:QT_DIR      = $qtHome
    $env:QTDIR       = $qtHome
    $env:QT_ROOT_DIR = $qtHome
    $env:Qt6_DIR     = Join-Path $qtHome 'lib\cmake\Qt6'
    if ($env:CMAKE_PREFIX_PATH -and ($env:CMAKE_PREFIX_PATH -notlike "*$qtHome*")) {
        $env:CMAKE_PREFIX_PATH = "$qtHome;$env:CMAKE_PREFIX_PATH"
    }
    elseif (-not $env:CMAKE_PREFIX_PATH) {
        $env:CMAKE_PREFIX_PATH = $qtHome
    }
    Add-ToPathFront (Join-Path $qtHome 'bin')

    $qtVersion = (& (Join-Path $qtHome 'bin\qmake.exe') -query QT_VERSION 2>$null | Select-Object -First 1)
    Write-Ok ("Qt {0}: {1}" -f $qtVersion, $qtHome)
    return $true
}

function Resolve-Wix {
    $candidates = @()
    if ($WixDir)   { $candidates += $WixDir }
    if ($env:WIX)  { $candidates += $env:WIX }

    foreach ($programFiles in @(${env:ProgramFiles(x86)}, $env:ProgramFiles)) {
        if (-not $programFiles) { continue }
        $dirs = Get-ChildItem -LiteralPath $programFiles -Directory -ErrorAction SilentlyContinue |
                Where-Object { $_.Name -like 'WiX Toolset v3*' } |
                Sort-Object Name -Descending
        foreach ($d in $dirs) { $candidates += $d.FullName }
    }

    foreach ($candidate in $candidates) {
        if (-not $candidate) { continue }
        $trimmed = $candidate.TrimEnd('\')
        if (Test-Path -LiteralPath (Join-Path $trimmed 'bin\candle.exe')) {
            $env:WIX = $trimmed
            Add-ToPathFront (Join-Path $trimmed 'bin')
            Write-Ok "WiX Toolset v3: $trimmed"
            return $true
        }
    }

    Write-Fail 'WiX Toolset v3 not found (needed to build the .msi).'
    Write-Note 'Install it with:  choco install -y wixtoolset     (or pass -WixDir <path>)'
    return $false
}

function Get-UuidGenPath {
    $roots = @()
    foreach ($programFiles in @(${env:ProgramFiles(x86)}, $env:ProgramFiles)) {
        if ($programFiles) { $roots += (Join-Path $programFiles 'Windows Kits\10\bin') }
    }

    $found = @()
    foreach ($root in $roots) {
        if (-not (Test-Path -LiteralPath $root)) { continue }
        $found += Get-ChildItem -LiteralPath $root -Filter 'uuidgen.exe' -Recurse -File -ErrorAction SilentlyContinue |
                  Where-Object { $_.DirectoryName -like '*\x64' }
    }

    if (-not $found) { return $null }
    return ($found | Sort-Object FullName -Descending | Select-Object -First 1).FullName
}

function Test-CMakeVersion {
    $cmakeExe = Get-CommandPath 'cmake.exe'
    if (-not $cmakeExe) {
        Write-Fail 'cmake not found.  choco install -y cmake  (and add it to PATH)'
        return $false
    }
    $line = (& $cmakeExe --version 2>$null | Select-Object -First 1)
    $version = $null
    if ($line -match '(\d+)\.(\d+)\.(\d+)') {
        $version = [version]("{0}.{1}.{2}" -f $matches[1], $matches[2], $matches[3])
    }
    if ($version -and $version -lt $MinCMakeVersion) {
        Write-Fail ("cmake {0} is too old, {1}+ is required." -f $version, $MinCMakeVersion)
        return $false
    }
    Write-Ok ("cmake {0}: {1}" -f $version, $cmakeExe)
    return $true
}

function Install-Prerequisites {
    $choco = Get-CommandPath 'choco.exe'
    if (-not $choco) {
        Write-Fail 'Chocolatey (choco) is not installed, cannot use -InstallPrereqs.'
        Write-Note 'See https://chocolatey.org/install , then re-run with -InstallPrereqs.'
        return
    }

    $packages = @()
    if (-not (Get-CommandPath 'git.exe'))   { $packages += 'git' }
    if (-not (Get-CommandPath 'cmake.exe')) { $packages += 'cmake' }
    if (-not (Get-CommandPath 'ninja.exe')) { $packages += 'ninja' }
    if (-not (Get-CommandPath '7z.exe'))    { $packages += '7zip' }
    if (-not $env:WIX -and -not (Get-CommandPath 'candle.exe')) { $packages += 'wixtoolset' }

    if (-not $packages) {
        Write-Ok 'All Chocolatey-installable tools are already present.'
        return
    }

    Write-Info ("choco install -y {0}" -f ($packages -join ' '))
    & $choco install -y @packages
    if ($LASTEXITCODE -ne 0) {
        Write-Warn "choco install returned $LASTEXITCODE - check the output above."
    }

    # Refresh PATH from the registry so the freshly installed tools are visible now.
    $machinePath = [Environment]::GetEnvironmentVariable('Path', 'Machine')
    $userPath    = [Environment]::GetEnvironmentVariable('Path', 'User')
    $env:PATH    = "$machinePath;$userPath;$env:PATH"
}

function Test-Prerequisites {
    Write-Step 'Checking prerequisites and preparing the environment'

    if ($InstallPrereqs) { Install-Prerequisites }

    $ok = $true

    # --- basic tools -------------------------------------------------------
    foreach ($tool in @(
        @{ Name = 'git.exe';   Hint = 'choco install -y git' },
        @{ Name = 'ninja.exe'; Hint = 'choco install -y ninja' },
        @{ Name = 'curl.exe';  Hint = 'ships with Windows 10/11 and Git for Windows' }
    )) {
        $path = Get-CommandPath $tool.Name
        if ($path) { Write-Ok ("{0}: {1}" -f $tool.Name, $path) }
        else { Write-Fail ("{0} not found.  {1}" -f $tool.Name, $tool.Hint); $ok = $false }
    }

    if (-not (Test-CMakeVersion)) { $ok = $false }

    # --- 7-Zip (setup.bat and the 7z package type need it) -----------------
    $sevenZip = Get-CommandPath '7z.exe'
    if (-not $sevenZip) {
        foreach ($guess in @('C:\Program Files\7-Zip', 'C:\Program Files (x86)\7-Zip')) {
            if (Test-Path -LiteralPath (Join-Path $guess '7z.exe')) {
                Add-ToPathFront $guess
                $sevenZip = Join-Path $guess '7z.exe'
                break
            }
        }
    }
    if ($sevenZip) { Write-Ok "7-Zip: $sevenZip" }
    else { Write-Fail '7z not found.  choco install -y 7zip'; $ok = $false }

    # --- bash / Visual Studio / Qt ----------------------------------------
    if (-not (Resolve-Bash))          { $ok = $false }
    if (-not (Resolve-VisualStudio))  { $ok = $false }
    if (-not (Resolve-Qt))            { $ok = $false }

    # --- WiX (only for msi / portable packaging) ---------------------------
    $needsWix = (-not $BuildOnly) -and (-not $CheckOnly) -and ($Portable -or ($BuildMode -in @('stable', 'testing')))
    if ($needsWix) {
        if (-not (Resolve-Wix)) { $ok = $false }
    }
    elseif ($env:WIX) {
        Write-Info "WIX = $env:WIX"
    }

    # --- Jack headers (installed by setup.bat) -----------------------------
    if (Test-Path -LiteralPath $JackDir) {
        Add-ToPathFront $JackDir
        Write-Ok "Jack: $JackDir"
    }
    else {
        Write-Info "Jack not installed yet (setup.bat will place it in '$JackDir')."
    }

    # --- dependencies bundle ----------------------------------------------
    if (Test-Path -LiteralPath $DepsDir) { Write-Ok "Dependencies: $DepsDir" }
    else { Write-Info "Dependencies not downloaded yet (setup.bat will fill '$DepsDir')." }

    # --- uuidgen (package.bat hard-codes an SDK path) ----------------------
    $uuidgen = Get-UuidGenPath
    if ($uuidgen) { Write-Ok "uuidgen: $uuidgen" }
    else { Write-Info 'uuidgen.exe not found in the Windows SDK - PowerShell will generate the product GUID.' }

    # --- disk space --------------------------------------------------------
    try {
        $driveName = (Get-Item -LiteralPath $RepoRoot).PSDrive.Name
        $freeGb    = [math]::Round((Get-PSDrive -Name $driveName).Free / 1GB, 1)
        if ($freeGb -lt $MinFreeGb) {
            Write-Warn ("Only {0} GB free on {1}: - a full build needs about {2} GB." -f $freeGb, $driveName, $MinFreeGb)
        }
        else {
            Write-Ok ("Free disk space on {0}: {1} GB" -f $driveName, $freeGb)
        }
    }
    catch { Write-Info 'Could not determine free disk space.' }

    # --- long paths --------------------------------------------------------
    try {
        $longPaths = (Get-ItemProperty -Path 'HKLM:\SYSTEM\CurrentControlSet\Control\FileSystem' `
                        -Name 'LongPathsEnabled' -ErrorAction SilentlyContinue).LongPathsEnabled
        if ($longPaths -ne 1) {
            Write-Warn 'Win32 long paths are disabled. Deep Qt/CMake paths may break the build.'
            Write-Note 'Fix: Set-ItemProperty "HKLM:\SYSTEM\CurrentControlSet\Control\FileSystem" LongPathsEnabled 1'
            $repoDepth = $RepoRoot.Length
            if ($repoDepth -gt 40) {
                Write-Warn ("The repository path is {0} characters long - consider moving it to C:\MuseScore." -f $repoDepth)
            }
        }
    }
    catch { }

    if (-not $ok) {
        throw 'Prerequisite check failed. Fix the [FAIL] items above and run the script again.'
    }

    Write-Ok 'All prerequisites satisfied.'
}

