#Requires -Version 5.1
<#
.SYNOPSIS
    One-shot builder for the Windows x64 setup (installer) of MuseScore Studio / Persian Tuner.

.DESCRIPTION
    This script automates the whole pipeline that is described in:
        docs/local-windows-x64-setup.md          (Persian setup guide)
        docs/windows-build-troubleshooting.md    (known errors and their fixes)

    It runs, in order:
        1.  Elevation check (re-launches itself as Administrator when needed)
        2.  Prerequisite detection (VS 2022 + MSVC x64, CMake, Ninja, 7-Zip, Git,
            Git Bash, Qt 6 msvc2022_64, WiX v3) and environment setup
        3.  git submodule update --init --recursive
        4.  buildscripts\ci\windows\setup.bat            (downloads dependencies + Jack)
        5.  make_build_mode_env.sh / make_build_number.sh (build metadata)
        6.  buildscripts\ci\windows\build.bat            (RelWithDebInfo + install)
        7.  buildscripts\ci\windows\package.bat          (.msi / .paf.exe / .7z)
        8.  checksum.sh + a summary of the produced artifacts

    Known problems from the troubleshooting guide that are handled automatically:
        *  "WSL ERROR: execvpe(/bin/bash) failed"  -> Git Bash is located and put in
           front of the WSL bash stub in PATH.
        *  Missing build.artifacts\env\*.env files -> generated (or regenerated for
           -PackageOnly) before the .bat scripts read them.
        *  Missing/renamed uuidgen.exe in the Windows SDK (package.bat has a hard
           coded 10.0.26100.0 path) -> the real uuidgen.exe is auto-detected, and if
           none exists the GUID is generated by PowerShell instead. The original
           package.bat is never modified; a patched copy is used from %TEMP%.
        *  package.bat started before build.release exists -> detected up front with
           a clear message instead of the confusing CMake / "File not found - WIX".

.PARAMETER BuildMode
    devel | nightly | testing | stable.  stable/testing produce an .msi,
    devel/nightly produce a .7z.  Default: stable.

.PARAMETER BuildNumber
    Build number used in the version string. Default: generated from the UTC date
    (same rule as make_build_number.sh, max 9 digits so WiX can fit it in an Int32).

.PARAMETER Portable
    Build the PortableApps (.paf.exe) flavour instead of the classic installer.

.PARAMETER QtDir
    Qt installation to use, e.g. C:\Qt\6.10.2\msvc2022_64.
    Auto-detected from QT_DIR / QTDIR / C:\Qt\* when omitted.

.PARAMETER WixDir
    WiX Toolset v3 root, e.g. "C:\Program Files (x86)\WiX Toolset v3.11".
    Auto-detected from %WIX% / Program Files when omitted.

.PARAMETER UpgradeGuid
    CPACK_WIX_UPGRADE_GUID. Keep it stable across releases so new MSIs upgrade
    older installations instead of installing side by side.

.PARAMETER DockWidgetsV2
    ON/OFF, passed to build.bat as --dockwidgets_v2. Default: ON (same as CI).

.PARAMETER InstallPrereqs
    Install the missing command line tools with Chocolatey
    (git, cmake, ninja, 7zip, wixtoolset). Qt and Visual Studio are never
    installed automatically.

.PARAMETER SkipDeps
    Do not run setup.bat (use when C:\musescore_dependencies is already populated).

.PARAMETER SkipSubmodules
    Do not run "git submodule update --init --recursive".

.PARAMETER BuildOnly
    Stop after build.bat, do not create the installer.

.PARAMETER PackageOnly
    Only run the packaging step on an existing build.release / build.install.

.PARAMETER CheckOnly
    Only run the prerequisite check and print the resolved environment.

.PARAMETER Clean
    Delete build.release, build.install, build.artifacts, msvc.build, msvc.install
    before building.

.PARAMETER Yes
    Do not ask anything, assume "yes" for every confirmation.

.PARAMETER NoElevate
    Do not try to re-launch as Administrator (fail instead).

.EXAMPLE
    .\build_setup_x64.ps1
    Full stable x64 MSI build with auto-detected tools.

.EXAMPLE
    .\build_setup_x64.ps1 -BuildMode stable -BuildNumber 2026090501 -QtDir C:\Qt\6.10.2\msvc2022_64

.EXAMPLE
    .\build_setup_x64.ps1 -Portable
    Build the PortableApps .paf.exe package.

.EXAMPLE
    .\build_setup_x64.ps1 -CheckOnly
    Just verify that the machine is ready to build.

.EXAMPLE
    .\build_setup_x64.ps1 -PackageOnly
    Re-create the installer from an existing build (fast, minutes instead of hours).

.NOTES
    Run from an elevated PowerShell. If the execution policy blocks the script:
        powershell -NoProfile -ExecutionPolicy Bypass -File .\build_setup_x64.ps1
    A full first build takes 2-4+ hours and needs ~30-50 GB of free disk space.
#>

[CmdletBinding()]
param(
    [ValidateSet('devel', 'nightly', 'testing', 'stable')]
    [string] $BuildMode = 'stable',

    [string] $BuildNumber = '',

    [switch] $Portable,

    [string] $QtDir = '',

    [string] $WixDir = '',

    [string] $UpgradeGuid = '11111111-1111-1111-1111-111111111111',

    [ValidateSet('ON', 'OFF')]
    [string] $DockWidgetsV2 = 'ON',

    [switch] $InstallPrereqs,
    [switch] $SkipDeps,
    [switch] $SkipSubmodules,
    [switch] $BuildOnly,
    [switch] $PackageOnly,
    [switch] $CheckOnly,
    [switch] $Clean,
    [switch] $Yes,
    [switch] $NoElevate
)

$ErrorActionPreference = 'Stop'

