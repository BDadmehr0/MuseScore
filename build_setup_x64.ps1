$DepsDir         = 'C:\musescore_dependencies'
$JackDir         = 'C:\Program Files (x86)\Jack'
$SetupBat        = 'buildscripts\ci\windows\setup.bat'
$BuildBat        = 'buildscripts\ci\windows\build.bat'
$PackageBat      = 'buildscripts\ci\windows\package.bat'
$MinFreeGb       = 40
$MinCMakeVersion = [version]'3.28'

$script:StepNo    = 0
